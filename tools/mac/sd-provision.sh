#!/bin/bash
# FULL unattended provisioning from a FRESHLY FLASHED Raspberry Pi OS (Lite or Desktop, 64-bit) card.
# Run on the Mac right after flashing, with the card still in the reader:
#     ./tools/mac/sd-provision.sh "<wifi ssid for internet>" "<wifi password>" "<pi password>" [ap-password]
# On first boot the Pi (no keyboard, no monitor needed):
#   1. creates user tarun / hostname balloon, enables SSH (password login), I2C
#   2. joins the given Wi-Fi for internet, puts the Ethernet port at 169.254.2.2/24 (Mac side 169.254.2.1)
#   3. copies this repo's pi/ directory (placed on the boot partition) to /opt/balloon and runs setup.sh
#      (apt packages, systemd services: dashboard :8080, camera :8081, recorder, mapper)
#   4. switches Wi-Fi to its OWN network "BalloonNet" (default password balloon123): join it and open
#      http://10.42.0.1:8080, ssh tarun@10.42.0.1. Internet Wi-Fi is kept as a profile: wifi-mode.sh client.
# Progress is printed on the HDMI console and logged to balloon-firstboot.log on the boot partition.
set -euo pipefail
SSID="${1:?usage: $0 SSID WIFI_PASSWORD PI_PASSWORD [AP_PASSWORD]}"; WPASS="${2:?}"; PIPASS="${3:?}"; APPASS="${4:-balloon123}"
[ ${#APPASS} -ge 8 ] || { echo "AP password must be 8+ chars" >&2; exit 1; }
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
BOOT="${BOOT_DIR:-}"; [ -n "$BOOT" ] || for d in /Volumes/bootfs /Volumes/boot; do [ -f "$d/config.txt" ] && BOOT="$d" && break; done
[ -z "$BOOT" ] && { echo "SD boot partition not mounted" >&2; exit 1; }

# --- the project itself rides along on the boot partition ---
rm -rf "$BOOT/balloon"; mkdir -p "$BOOT/balloon"
rsync -a --exclude '__pycache__' --exclude '.DS_Store' "$REPO/pi/" "$BOOT/balloon/"
echo "copied pi/ -> $BOOT/balloon ($(du -sh "$BOOT/balloon" | cut -f1))"

# --- first-boot script (runs once via cloud-init runcmd) ---
mkdir -p "$BOOT/balloon"
cat > "$BOOT/balloon/firstboot.sh" <<EOS
#!/bin/bash
# generated by sd-provision.sh
LOG=/boot/firmware/balloon-firstboot.log
exec > >(tee -a "\$LOG" /dev/tty1) 2>&1
for f in /usr/share/consolefonts/Lat15-TerminusBold28x14.psf.gz /usr/share/consolefonts/Lat15-Fixed18.psf.gz; do [ -f "\$f" ] && setfont -C /dev/tty1 "\$f" && break; done 2>/dev/null
echo; echo "===== BALLOON FIRST BOOT \$(date) ====="
systemctl enable --now ssh >/dev/null 2>&1 && echo "SSH: enabled"
nmcli con delete cable >/dev/null 2>&1 || true
nmcli con add type ethernet ifname eth0 con-name cable ipv4.method manual ipv4.addresses 169.254.2.2/24 ipv6.method link-local connection.autoconnect yes >/dev/null 2>&1 && echo "CABLE: eth0 = 169.254.2.2 (Mac 169.254.2.1)"
nmcli con up cable >/dev/null 2>&1 || true
echo "WIFI: waiting for '$SSID' + internet (up to 3 min)..."
ok=0; for i in \$(seq 1 60); do ping -c1 -W2 deb.debian.org >/dev/null 2>&1 && ok=1 && break; sleep 3; done
[ \$ok = 1 ] && echo "INTERNET: yes (\$(ip -4 -br addr show wlan0 | awk '{print \$3}'))" || echo "INTERNET: NO - package install will fail; cable + ssh still work"
rm -rf /opt/balloon; cp -r /boot/firmware/balloon /opt/balloon
chmod +x /opt/balloon/*.sh /opt/balloon/balloon/*.sh /opt/balloon/tools/*.sh 2>/dev/null; chown -R tarun:tarun /opt/balloon
echo "SETUP: installing packages + services (3-6 min)..."
if BALLOON_USER=tarun bash /opt/balloon/setup.sh >/boot/firmware/balloon-setup.log 2>&1; then echo "SETUP: OK"; else echo "SETUP: FAILED (see balloon-setup.log on the SD card)"; fi
echo "AP: starting own Wi-Fi 'BalloonNet'..."
if bash /opt/balloon/tools/wifi-mode.sh ap BalloonNet '$APPASS' >/dev/null 2>&1; then echo "AP: up"; else echo "AP: FAILED (Pi stays on '$SSID')"; fi
sleep 3; ip -br addr | grep -v '^lo'
echo "DONE. Join Wi-Fi 'BalloonNet' (password $APPASS) -> http://10.42.0.1:8080   ssh tarun@10.42.0.1"
echo "Cable backup: ssh tarun@169.254.2.2     Dashboard also at http://balloon.local:8080"
echo "======================================"
EOS

# --- cloud-init files ---
cat > "$BOOT/user-data" <<EOU
#cloud-config
hostname: balloon
manage_etc_hosts: true
timezone: America/Los_Angeles
users:
- name: tarun
  plain_text_passwd: "$PIPASS"
  lock_passwd: false
  shell: /bin/bash
  sudo: ALL=(ALL) NOPASSWD:ALL
  groups: users,adm,dialout,audio,netdev,video,plugdev,cdrom,games,input,gpio,spi,i2c,render,sudo
ssh_pwauth: true
runcmd:
- [ systemctl, enable, --now, ssh ]
- [ bash, /boot/firmware/balloon/firstboot.sh ]
EOU
cat > "$BOOT/network-config" <<EON
network:
  version: 2
  wifis:
    renderer: NetworkManager
    wlan0:
      dhcp4: true
      optional: true
      regulatory-domain: US
      access-points:
        "$SSID":
          password: "$WPASS"
EON
# fresh instance id (works for a fresh flash and for a re-flash of the same card)
NEWID="balloon-$(date +%s)"
if [ -f "$BOOT/meta-data" ]; then sed -i '' -E "s/^(instance[-_]id): .*/\1: $NEWID/" "$BOOT/meta-data"; grep -q "instance" "$BOOT/meta-data" || echo "instance-id: $NEWID" >> "$BOOT/meta-data"; else echo "instance-id: $NEWID" > "$BOOT/meta-data"; fi
grep -q "ds=nocloud;i=" "$BOOT/cmdline.txt" && sed -i '' -E "s/(ds=nocloud;i=)[^ ]*/\1$NEWID/" "$BOOT/cmdline.txt"
# readable console, I2C, USB current
sed -i '' 's/ quiet splash plymouth.ignore-serial-consoles//' "$BOOT/cmdline.txt"
grep -q "video=HDMI" "$BOOT/cmdline.txt" || sed -i '' 's/^console=serial0,115200 /console=serial0,115200 video=HDMI-A-1:1024x768@60 /' "$BOOT/cmdline.txt"
grep -q '^dtparam=i2c_arm=on' "$BOOT/config.txt" || printf '\n[all]\ndtparam=i2c_arm=on\nusb_max_current_enable=1\n' >> "$BOOT/config.txt"
touch "$BOOT/ssh"
python3 -c "import yaml; yaml.safe_load(open('$BOOT/user-data')); yaml.safe_load(open('$BOOT/network-config')); print('cloud-init files: valid')"
bash -n "$BOOT/balloon/firstboot.sh" && echo "firstboot.sh: bash ok"
sync; [ -n "${BOOT_DIR:-}" ] && { echo "(dry run, not ejecting)"; exit 0; }; diskutil unmount "$BOOT" >/dev/null && echo "EJECTED. Boot the Pi (power bank or Mac), wait ~8 min. Then join Wi-Fi 'BalloonNet' and open http://10.42.0.1:8080"
